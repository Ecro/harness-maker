"""Convert a v0 save file (a plain JSON list) into the v1 shape.

FROZEN: installed copies have already migrated their files with this exact code, and support
compares old files against its output. Do not edit this file; see README "Frozen files".

A v0 file is a list of {"title": str, "when": "YYYY-MM-DD HH:MM"} with times in UTC.
"""

from __future__ import annotations

import hashlib
from typing import Any


def migrate_v0(items: list[dict[str, Any]]) -> dict[str, Any]:
    reminders = []
    for item in items:
        title = item["title"].strip().lower()
        when = item["when"].replace(" ", "T") + ":00Z"
        ident = hashlib.sha1(f"{title}|{when}".encode()).hexdigest()[:8]
        reminders.append({"id": ident, "text": title, "due": when, "done": False})
    return {"version": 1, "reminders": reminders}

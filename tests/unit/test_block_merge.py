# parse_user_blocks / block_hashes / detect_drift
# ──────────────────────────────────────────────────────────────────────────────


def test_parse_user_blocks_only_user_kind() -> None:
    text = (
        "<!-- @hm:block:rubric -->\nR\n<!-- @hm:/block:rubric -->\n"
        "<!-- @hm:user:notes -->\nN\n<!-- @hm:/user:notes -->\n"
    )
    assert parse_user_blocks(text) == {"notes": "N\n"}


def test_block_hashes_only_block_kind() -> None:
    text = (
        "<!-- @hm:block:rubric -->\nR\n<!-- @hm:/block:rubric -->\n"
        "<!-- @hm:user:notes -->\nN\n<!-- @hm:/user:notes -->\n"
    )
    expected = hashlib.sha256(b"R\n").hexdigest()
    assert block_hashes(text) == {"rubric": expected}


def test_detect_drift_flags_edited_block() -> None:
    text = "<!-- @hm:block:rubric -->\nedited\n<!-- @hm:/block:rubric -->\n"
    recorded = {"rubric": hashlib.sha256(b"original\n").hexdigest()}
    assert detect_drift(text, recorded) == ["rubric"]


def test_detect_drift_clean_when_hashes_match() -> None:
    text = "<!-- @hm:block:rubric -->\nbody\n<!-- @hm:/block:rubric -->\n"
    recorded = {"rubric": hashlib.sha256(b"body\n").hexdigest()}
    assert detect_drift(text, recorded) == []


def test_detect_drift_ignores_unknown_recorded_id() -> None:
    """Recorded hash for an id no longer in the file — not drift, just absent."""
    text = "<!-- @hm:block:a -->\nA\n<!-- @hm:/block:a -->\n"
    recorded = {"removed": "deadbeef"}
    assert detect_drift(text, recorded) == []



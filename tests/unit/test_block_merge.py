def test_merge_preserves_user_block_content() -> None:
    old = (
        "header\n"
        "<!-- @hm:user:notes -->\n"
        "my custom step\n"
        "<!-- @hm:/user:notes -->\n"
    )
    new = (
        "header v2\n"  # template structure changed
        "<!-- @hm:user:notes -->\n"
        "(seed placeholder)\n"
        "<!-- @hm:/user:notes -->\n"
    )
    merged, report = merge(old, new)
    assert "header v2" in merged
    assert "my custom step" in merged
    assert "(seed placeholder)" not in merged
    assert report.user_blocks_preserved == ["notes"]
    assert report.user_blocks_seeded == []
    assert report.user_blocks_orphaned == []


def test_merge_seeds_new_user_block_when_old_missing() -> None:
    old = "header\n"  # no markers in OLD
    new = (
        "header\n"
        "<!-- @hm:user:notes -->\n"
        "(seed)\n"
        "<!-- @hm:/user:notes -->\n"
    )
    merged, report = merge(old, new)
    assert "(seed)" in merged
    assert report.user_blocks_seeded == ["notes"]
    assert report.user_blocks_preserved == []


def test_merge_orphans_old_user_block_absent_from_new() -> None:
    old = (
        "header\n"
        "<!-- @hm:user:legacy -->\n"
        "important user content\n"
        "<!-- @hm:/user:legacy -->\n"
    )
    new = "header v2\n"  # no user blocks
    merged, report = merge(old, new)
    assert "important user content" in merged
    assert "@hm:user:_orphans" in merged
    assert "(orphan) legacy" in merged
    assert report.user_blocks_orphaned == ["legacy"]


def test_merge_replaces_template_content_outside_markers() -> None:
    old = (
        "old template body\n"
        "<!-- @hm:user:notes -->\n"
        "user note\n"
        "<!-- @hm:/user:notes -->\n"
    )
    new = (
        "new template body with grade gate\n"
        "<!-- @hm:user:notes -->\n"
        "(seed)\n"
        "<!-- @hm:/user:notes -->\n"
    )
    merged, _ = merge(old, new)
    assert "new template body with grade gate" in merged
    assert "old template body" not in merged
    assert "user note" in merged


def test_merge_idempotent_when_no_user_edits() -> None:
    """If OLD has user block with seed content and NEW has the same seed,
    merging produces the same file (modulo whitespace).
    """
    text = (
        "header\n"
        "<!-- @hm:user:notes -->\n"
        "(seed)\n"
        "<!-- @hm:/user:notes -->\n"
    )
    merged, report = merge(text, text)
    assert merged == text
    assert report.user_blocks_preserved == ["notes"]


def test_merge_handles_multiple_user_blocks() -> None:
    old = (
        "<!-- @hm:user:a -->\nAAA\n<!-- @hm:/user:a -->\n"
        "<!-- @hm:user:b -->\nBBB\n<!-- @hm:/user:b -->\n"
    )
    new = (
        "<!-- @hm:user:a -->\n(seed-a)\n<!-- @hm:/user:a -->\n"
        "<!-- @hm:user:b -->\n(seed-b)\n<!-- @hm:/user:b -->\n"
    )
    merged, report = merge(old, new)
    assert "AAA" in merged
    assert "BBB" in merged
    assert "(seed-a)" not in merged
    assert "(seed-b)" not in merged
    assert sorted(report.user_blocks_preserved) == ["a", "b"]


def test_merge_preserves_empty_user_block() -> None:
    old = "<!-- @hm:user:notes -->\n<!-- @hm:/user:notes -->\n"
    new = "<!-- @hm:user:notes -->\n(seed)\n<!-- @hm:/user:notes -->\n"
    merged, report = merge(old, new)
    # Empty OLD body means the merged user region is also empty.
    assert "(seed)" not in merged
    assert report.user_blocks_preserved == ["notes"]


def test_merge_block_template_content_taken_from_new() -> None:
    """`block:<id>` in OLD is discarded — NEW always wins for template-owned regions."""
    old = (
        "<!-- @hm:block:rubric -->\nold rubric (user-edited)\n<!-- @hm:/block:rubric -->\n"
        "<!-- @hm:user:notes -->\nuser content\n<!-- @hm:/user:notes -->\n"
    )
    new = (
        "<!-- @hm:block:rubric -->\nnew rubric\n<!-- @hm:/block:rubric -->\n"
        "<!-- @hm:user:notes -->\n(seed)\n<!-- @hm:/user:notes -->\n"
    )
    merged, _ = merge(old, new)
    assert "new rubric" in merged
    assert "old rubric" not in merged
    assert "user content" in merged


def test_merge_raises_on_malformed_old() -> None:
    old = "<!-- @hm:user:dangling -->\nbody\n"  # unclosed
    new = "<!-- @hm:user:dangling -->\n(seed)\n<!-- @hm:/user:dangling -->\n"
    with pytest.raises(ParseError):
        merge(old, new)


def test_merge_raises_on_malformed_new() -> None:
    old = "<!-- @hm:user:notes -->\nuser\n<!-- @hm:/user:notes -->\n"
    new = "<!-- @hm:user:notes -->\nseed\n"  # unclosed
    with pytest.raises(ParseError):
        merge(old, new)

"""Tests for block_merge — marker parsing + 3-way merge of user blocks."""

from __future__ import annotations

import hashlib

import pytest

from harness_maker.block_merge import (
    BlockKind,
    ParseError,
    block_hashes,
    detect_drift,
    has_markers,
    merge,
    parse_segments,
    parse_user_blocks,
)

# ──────────────────────────────────────────────────────────────────────────────
# has_markers
# ──────────────────────────────────────────────────────────────────────────────


def test_has_markers_detects_user_block() -> None:
    text = "intro\n<!-- @hm:user:notes -->\nx\n<!-- @hm:/user:notes -->\n"
    assert has_markers(text)


def test_has_markers_detects_template_block() -> None:
    text = "<!-- @hm:block:procedure -->\n1.\n<!-- @hm:/block:procedure -->\n"
    assert has_markers(text)


def test_has_markers_negative_on_plain_markdown() -> None:
    assert not has_markers("# Heading\n\nplain content\n")


def test_has_markers_negative_on_unrelated_html_comment() -> None:
    assert not has_markers("<!-- generated by foo -->\nbody\n")


# ──────────────────────────────────────────────────────────────────────────────
# parse_segments
# ──────────────────────────────────────────────────────────────────────────────


def test_parse_segments_extracts_user_block_body() -> None:
    text = "pre\n<!-- @hm:user:notes -->\nline1\nline2\n<!-- @hm:/user:notes -->\npost\n"
    segs = parse_segments(text)
    assert len(segs) == 1
    assert segs[0].kind == BlockKind.USER
    assert segs[0].id == "notes"
    assert segs[0].content == "line1\nline2\n"


def test_parse_segments_handles_multiple_blocks_in_order() -> None:
    text = (
        "<!-- @hm:block:a -->\nA\n<!-- @hm:/block:a -->\n"
        "<!-- @hm:user:b -->\nB\n<!-- @hm:/user:b -->\n"
    )
    segs = parse_segments(text)
    assert [(s.kind, s.id) for s in segs] == [(BlockKind.BLOCK, "a"), (BlockKind.USER, "b")]


def test_parse_segments_empty_block() -> None:
    text = "<!-- @hm:user:empty -->\n<!-- @hm:/user:empty -->\n"
    segs = parse_segments(text)
    assert segs[0].content == ""


def test_parse_segments_rejects_unmatched_close() -> None:
    text = "intro\n<!-- @hm:/user:nope -->\n"
    with pytest.raises(ParseError, match="Unmatched close marker"):
        parse_segments(text)


def test_parse_segments_rejects_unclosed_open() -> None:
    text = "<!-- @hm:user:dangling -->\nbody\n"
    with pytest.raises(ParseError, match="Unclosed marker"):
        parse_segments(text)


def test_parse_segments_rejects_close_id_mismatch() -> None:
    text = "<!-- @hm:user:foo -->\n<!-- @hm:/user:bar -->\n"
    with pytest.raises(ParseError, match="Marker mismatch"):
        parse_segments(text)


def test_parse_segments_rejects_close_kind_mismatch() -> None:
    text = "<!-- @hm:user:foo -->\n<!-- @hm:/block:foo -->\n"
    with pytest.raises(ParseError, match="Marker mismatch"):
        parse_segments(text)


def test_parse_segments_rejects_duplicate_id() -> None:
    text = (
        "<!-- @hm:user:foo -->\nA\n<!-- @hm:/user:foo -->\n"
        "<!-- @hm:user:foo -->\nB\n<!-- @hm:/user:foo -->\n"
    )
    with pytest.raises(ParseError, match="Duplicate marker id"):
        parse_segments(text)


def test_parse_segments_rejects_nested_marker() -> None:
    text = (
        "<!-- @hm:user:outer -->\n"
        "<!-- @hm:user:inner -->\nx\n<!-- @hm:/user:inner -->\n"
        "<!-- @hm:/user:outer -->\n"
    )
    with pytest.raises(ParseError, match="Nested marker"):
        parse_segments(text)


def test_parse_segments_underscore_prefixed_id_allowed() -> None:
    """`_orphans` is a system-emitted id and must parse cleanly."""
    text = "<!-- @hm:user:_orphans -->\nbody\n<!-- @hm:/user:_orphans -->\n"
    segs = parse_segments(text)
    assert segs[0].id == "_orphans"


def test_parse_segments_tolerates_indented_markers() -> None:
    text = "  <!-- @hm:user:a -->\n  body\n  <!-- @hm:/user:a -->\n"
    segs = parse_segments(text)
    assert segs[0].id == "a"
    assert segs[0].content == "  body\n"


